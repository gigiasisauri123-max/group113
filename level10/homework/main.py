#გააკეთეთ 5-5 მაგალითი თთოეულ შედარების ოპერატორზე (>, >=, <, <=, ==, !=), გვერდზე კომენტარის საშვალებით მიუთითეთ თუ რომელ boolean მნიშვნელობას გამოიტანას, აიღეთ მრავალფეროვანი კომბინაციები, შეეცადეთ გქონდეთ ყველა ვარიანტი

#> მეტობა boolian
print(5 > 3)  # True
print(9 > 8)  # True
print(2 > 1)  # True
print(4 > 0)  # True
print(7 > 5)  # True

#< ნაკლებობა boolian
print(3 < 5)  # True
print(1 < 2)  # True
print(0 < 4)  # True
print(6 < 7)  # True
print(8 < 9)  # True

#>= მეტობა ან ტოლი boolian
print(5 >= 5)  # True
print(7 >= 6)  # True
print(3 >= 2)  # True 
print(4 >= 4)  # True
print(9 >= 8)  # True

#<= ნაკლებობა ან ტოლი boolian
print(2 <= 3)  # True
print(5 <= 5)  # True
print(1 <= 4)  # True
print(0 <= 0)  # True
print(6 <= 7)  # True

#== ტოლი boolian
print(5 == 5)  # True
print(3 == 3)  # True
print(7 == 7)  # True
print(2 == 2)  # True
print(4 == 4)  # True

#!= არ ტოლი boolian
print(5 != 3)  # True
print(7 != 8)  # True
print(2 != 1)  # True
print(4 != 0)  # True
print(6 != 5)  # True

