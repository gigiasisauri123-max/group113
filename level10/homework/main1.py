# შექმენით 5 ცვლადი, რომლებშიც შეინახავთ განსხვავებულ შედარების ოპერაციათა შედეგებს, შედარების ოპერაციას გვერდზე კომენტარის საშვალებით მიუწერეთ მისი შედეგი (boolean მნიშვნელობა) და ახსენით რა განსხვავებაა ოპერატორსა და ოპერაციას შორის

info1 = (10 > 5) # true მეტობის შედდარების შედეგი 10 > 5 არის true, რადგან 10 მეტია 5-ზე
info2 = (3 < 7) # true ნაკლებობის შედარების შედეგი 3 < 7 არის true, რადგან 3 ნაკლებია 7-ზე
info3 = (4 == 4) # true ტოლობის შედარების შედეგი 4 == 4 არის true, რადგან ორივე მხარე ტოლია
info4 = (6 != 2) # true არ ტოლობის შედარების შედეგი 6 != 2 არის true, რადგან 6 არ ტოლია 2-ს
info5 = (8 >= 8) # true მეტობის ან ტოლობის შედარების შედეგი 8 >= 8 არის true, რადგან 8 მეტია ან ტოლია 8-ს

