# ლოგიური ოპერატორების ყველა მაგალითი დაწერე პითონში, ესეიგი  not operator-ზე 2 მაგალითი, ხოლო or და and ოპერატორებზე 4 მაგალითი. დაბეჭდეთ თითოეულის შედეგი ყველა მაგლითში უნდა იყოს სხვდასხვა კომბინაცია true და false მნიშვნელობების. გვერდზე კომენტარის სახით მიუწერეთ პასუხი

# not operator-ის მაგალითები
print(not True)  # False
print(not False)  #  True

# or operator-ის მაგალითები
print(True or False)  # True
print(False or True)  #  True
print(False or False)  # False
print(True or True)  # True

# and operator-ის მაგალითები
print(True and False)  # False
print(False and True)  # False
print(True and True)  # True
print(False and False)  # False
