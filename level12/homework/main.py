#2) გააკეთეთ 5-5 მაგალითი თთოეულ შედარების ოპერატორზე (>, >=, <, <=, ==, !=), გვერდზე კომენტარის საშვალებით მიუთითეთ თუ რომელ boolean მნიშვნელობას გამოიტანას, აიღეთ მრავალფეროვანი კომბინაციები, შეეცადეთ გქონდეთ ყველა ვარიანტი

# >
print(5 > 3)  # True
print(2 > 4)  # False
print(10 > 10)  # False
print(15 > 12)  # false
print(9 > 4) # true

# >=
print( 7 >= 7) #  true
print(4 >= 9) #  false
print(20 >= 15) #  true
print(18 >= 5) #  true
print(22 >= 22) #  true

# <
print(6 > 7) #  false
print(16 > 1) #  true
print(20 > 25) #  false
print(25 > 19) #  true
print(14 > 13)

# <=
print(15 <= 17) #  true
print(20 <= 11) #  false
print(5 <= 23) #  true
print(10 <= 7) #  false
print(25 <= 30) #  true

# ==
print(15 == 15) #  true
print(12 == 13) # false
print(21 == 21) #  true
print(13 == 22) #  false
print(5 == 5) #  true

# !=
print(15 != 15) # false
print(5 != 12) # true
print(22 != 22) #  false
print(23 != 32) #  true
print(10 != 10) # false